def solution(food):
    # 푸드 파이트 대회
    # 선수들은 1대1로 대결하며, 매 대결마다 음식의 종류와 양이 바뀜
    # 대결은 준비된 음식들을 일렬로 배치한 뒤, 한 선수는 제일 왼쪽에 있는 음식부터 오른쪽으로
    # 다른 선수는 제일 오른쪽에 있는 음식부터 왼쪽으로 순서대로 먹는 방식으로 진행
    # 중앙에는 물을 배치하고, 물을 먼저 먹는 선수가 승리
    
    # 1. 한 사람이 먹을 수 있는 개수를 담을 tmp 리스트 생성합니다.
    
    # 2. food의 첫 번째 원소는 물이기 때문에, 두 번째 원소부터 for문을 돕니다.
    
    # 3. i번째 있는 원소의 값들을 기반으로 한 사람 당 먹을 수 있는 개수를 구합니다.
      # 만약 3이면 둘이서 서로 1개씩 먹을 수 있습니다. 6이면 둘이서 서로 3개씩 먹을 수 있습니다.
      # 그래서 // 몫 연산자를 통해 한 사람 당 먹을 수 있는 개수를 구합니다.
    
    # 4. 한 사람 당 먹을 수 있는 개수를 one_person_eating 변수에 선언하고, 이를 기반으로 그 만큼 for 문을 돌려서 tmp 리스트에 담습니다.
      # 만약 i가 1인 음식을 3개 먹을 수 있다면 tmp에 [1, 1, 1]의 형식으로 담습니다.
    
    # 5. 한 사람이 먹을 수 있는 음식의 개수를 모두 구했고, 이를 0과 tmp[::-1]을 돌린 것을 기반으로 전체 푸드 파이트 대회 형식에 맞는 답을 구합니다. (물은 항상 1입니다.)
    
    tmp = []
    for i in range(1, len(food)):
        one_person_eating = food[i] // 2 
        for j in range(one_person_eating):
            tmp.append(str(i))
    
    result = tmp + ["0"] + tmp[::-1]
    
    return "".join(result)