SELECT DEPARTMENT_NAME AS 'DEPARTMENT'
     , NAME AS 'EMPLOYEE'
     , SALARY
FROM (
    SELECT E.*
         , D.NAME AS 'DEPARTMENT_NAME'
         , DENSE_RANK() OVER(PARTITION BY E.DEPARTMENTID ORDER BY E.SALARY DESC) AS RNK
    FROM EMPLOYEE AS E
      INNER JOIN DEPARTMENT AS D ON E.DEPARTMENTID = D.ID
) AS RANK_TABLE
WHERE RNK <= 3;